download_file() {
    local url="$1"
    local destination="$2"

    mkdir -p "$(dirname "${destination}")"

    echo "Downloading:"
    echo "  ${url}"
    echo "To:"
    echo "  ${destination}"

    curl \
        --fail \
        --silent \
        --show-error \
        --location \
        --retry 4 \
        --retry-delay 2 \
        --connect-timeout 30 \
        --max-time 600 \
        "${url}" \
        --output "${destination}"
}

