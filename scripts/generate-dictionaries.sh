download_german_frequency() {
    local archive="${WORK_DIR}/leipzig/deu_news_2025_1M.tar.gz"
    local extract_dir="${WORK_DIR}/leipzig/extracted"

    mkdir -p "${WORK_DIR}/leipzig"

    rm -rf "${extract_dir}"
    mkdir -p "${extract_dir}"

    download_file \
        "${LEIPZIG_DE_URL}" \
        "${archive}"

    echo "Extracting German Leipzig corpus..."

    tar \
        --extract \
        --gzip \
        --file="${archive}" \
        --directory="${extract_dir}"

    local corpus_file=""

    corpus_file="$(
        find "${extract_dir}" \
            -type f \
            \( -name "*.txt" -o -name "*.csv" \) \
            -print \
            -quit
    )"

    if [[ -z "${corpus_file}" ]]; then
        corpus_file="$(
            find "${extract_dir}" \
                -type f \
                -print \
                -quit
        )"
    fi

    [[ -n "${corpus_file}" ]] || die "Could not find German Leipzig corpus file."

    printf '%s\n' "${corpus_file}" > "${WORK_DIR}/leipzig/corpus_path.txt"

    echo "German corpus:"
    echo "  ${corpus_file}"
}

