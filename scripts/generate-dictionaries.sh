# ------------------------------------------------------------
# Generate delete candidates
#
# IMPORTANT:
# Deletes are generated ONLY from the final .dict vocabulary.
# Delete keys are NEVER fed back into vocabulary generation.
# ------------------------------------------------------------

generate_deletes() {
    local dictionary="$1"
    local deletes="$2"
    local language="$3"
    local budget="$4"

    python3 - "${dictionary}" "${deletes}" "${language}" "${budget}" "${TOP_DISTANCE2_WORDS}" "${MAX_DELETE_WORD_LENGTH}" "${MAX_DELETES_PER_WORD}" <<'PY'
import sys
import unicodedata
from pathlib import Path

dictionary = Path(sys.argv[1])
deletes = Path(sys.argv[2])
language = sys.argv[3]
budget = int(sys.argv[4])
top_distance2 = int(sys.argv[5])
max_word_length = int(sys.argv[6])
max_deletes_per_word = int(sys.argv[7])

def normalize_word(word):
    return unicodedata.normalize("NFC", word)

words = []

with dictionary.open(
    "r",
    encoding="utf-8",
    errors="strict"
) as fh:

    for raw in fh:
        word = raw.rstrip("\r\n")

        if not word:
            continue

        if word.startswith("#"):
            continue

        words.append(normalize_word(word))

# Dictionary order is intentionally preserved.
# The first TOP_DISTANCE2 words receive distance-2 coverage.
distance2_words = words[:top_distance2]

mapping = {}
entry_count = 0

def add_delete(delete_key, target):
    global entry_count

    if entry_count >= budget:
        return False

    if not delete_key:
        return True

    if delete_key not in mapping:
        mapping[delete_key] = target
        entry_count += 1

        if entry_count >= budget:
            return False

    return True

def generate_distance1(word):
    generated = 0

    for index in range(len(word)):
        delete_key = word[:index] + word[index + 1:]

        before = len(mapping)

        if not add_delete(delete_key, word):
            return generated

        if len(mapping) > before:
            generated += 1

            if generated >= max_deletes_per_word:
                break

    return generated

def generate_distance2(word):
    generated = 0

    first_level = set()

    for index in range(len(word)):
        delete_key = word[:index] + word[index + 1:]
        first_level.add(delete_key)

    for intermediate in sorted(first_level):
        for index in range(len(intermediate)):
            delete_key = (
                intermediate[:index] +
                intermediate[index + 1:]
            )

            before = len(mapping)

            if not add_delete(delete_key, word):
                return generated

            if len(mapping) > before:
                generated += 1

                if generated >= max_deletes_per_word:
                    return generated

    return generated

# ------------------------------------------------------------
# Distance 2 first for high-priority vocabulary.
# ------------------------------------------------------------

for word in distance2_words:
    if entry_count >= budget:
        break

    if len(word) > max_word_length:
        continue

    generate_distance2(word)

# ------------------------------------------------------------
# Distance 1 for the complete final dictionary.
# ------------------------------------------------------------

for word in words:
    if entry_count >= budget:
        break

    if len(word) > max_word_length:
        continue

    generate_distance1(word)

# ------------------------------------------------------------
# Write deterministic delete index.
# ------------------------------------------------------------

with deletes.open(
    "w",
    encoding="utf-8",
    newline="\n"
) as dst:

    dst.write("#POCKETBOARD-DELETES-1\n")
    dst.write("#distance=1,2\n")
    dst.write("#source=dict-only\n")
    dst.write("#delete<TAB>target\n")

    for delete_key in sorted(mapping):
        dst.write(delete_key)
        dst.write("\t")
        dst.write(mapping[delete_key])
        dst.write("\n")

print(f"Generated deletes: {entry_count}")
PY
}

# ------------------------------------------------------------
# Validate dictionary format
# ------------------------------------------------------------

validate_dictionary() {
    local dictionary="$1"
    local language="$2"

    print_section "Checking dictionary: ${language}"

    python3 - "${dictionary}" "${language}" <<'PY'
import sys
import unicodedata
from pathlib import Path

dictionary = Path(sys.argv[1])
language = sys.argv[2]

if not dictionary.is_file():
    raise SystemExit(f"ERROR: Missing dictionary: {dictionary}")

words = []
seen = set()

with dictionary.open(
    "r",
    encoding="utf-8",
    errors="strict"
) as fh:

    lines = fh.readlines()

if not lines:
    raise SystemExit(
        f"ERROR: Empty dictionary: {dictionary}"
    )

if lines[0].rstrip("\r\n") != "#POCKETBOARD-DICT-1":
    raise SystemExit(
        f"ERROR: Invalid dictionary header: {dictionary}"
    )

for raw in lines[1:]:
    word = raw.rstrip("\r\n")

    if not word:
        raise SystemExit(
            f"ERROR: Empty dictionary entry: {dictionary}"
        )

    if word.startswith("#"):
        raise SystemExit(
            f"ERROR: Unexpected comment after header: {dictionary}"
        )

    normalized = unicodedata.normalize("NFC", word)

    if normalized != word:
        raise SystemExit(
            f"ERROR: Dictionary entry is not NFC-normalized: "
            f"{language}: {word}"
        )

    if any(ch.isspace() for ch in word):
        raise SystemExit(
            f"ERROR: Dictionary entry contains whitespace: "
            f"{language}: {word}"
        )

    if word in seen:
        raise SystemExit(
            f"ERROR: Duplicate dictionary word: "
            f"{language}: {word}"
        )

    seen.add(word)
    words.append(word)

if not words:
    raise SystemExit(
        f"ERROR: Dictionary contains no words: {dictionary}"
    )

print(f"Dictionary validation OK: {len(words)} words")
PY
}

# ------------------------------------------------------------
# Validate deletes
# ------------------------------------------------------------

validate_delete_format() {
    local deletes="$1"
    local dictionary="$2"
    local language="$3"

    print_section "Checking deletes: ${language}"

    python3 - "${deletes}" "${dictionary}" "${language}" <<'PY'
import sys
import unicodedata
from pathlib import Path

deletes = Path(sys.argv[1])
dictionary = Path(sys.argv[2])
language = sys.argv[3]

if not deletes.is_file():
    raise SystemExit(
        f"ERROR: Missing deletes file: {deletes}"
    )

if not dictionary.is_file():
    raise SystemExit(
        f"ERROR: Missing dictionary: {dictionary}"
    )

with dictionary.open(
    "r",
    encoding="utf-8",
    errors="strict"
) as fh:

    dictionary_words = {
        line.rstrip("\r\n")
        for line in fh
        if line.rstrip("\r\n")
        and not line.startswith("#")
    }

with deletes.open(
    "r",
    encoding="utf-8",
    errors="strict"
) as fh:

    lines = fh.readlines()

if len(lines) < 4:
    raise SystemExit(
        f"ERROR: Deletes file is too short: {deletes}"
    )

expected_headers = [
    "#POCKETBOARD-DELETES-1",
    "#distance=1,2",
    "#source=dict-only",
    "#delete<TAB>target",
]

for index, expected in enumerate(expected_headers):
    actual = lines[index].rstrip("\r\n")

    if actual != expected:
        raise SystemExit(
            f"ERROR: Invalid deletes header at line {index + 1}: "
            f"{language}: {actual!r}"
        )

seen_delete_keys = set()
entry_count = 0

for line_number, raw in enumerate(lines[4:], start=5):
    line = raw.rstrip("\r\n")

    if not line:
        raise SystemExit(
            f"ERROR: Empty delete entry at line {line_number}: "
            f"{language}"
        )

    if "\t" not in line:
        raise SystemExit(
            f"ERROR: Delete entry without TAB at line "
            f"{line_number}: {language}"
        )

    delete_key, target = line.split("\t", 1)

    if not delete_key:
        raise SystemExit(
            f"ERROR: Empty delete key at line {line_number}: "
            f"{language}"
        )

    if not target:
        raise SystemExit(
            f"ERROR: Empty delete target at line {line_number}: "
            f"{language}"
        )

    delete_key = unicodedata.normalize(
        "NFC",
        delete_key
    )

    target = unicodedata.normalize(
        "NFC",
        target
    )

    if target not in dictionary_words:
        raise SystemExit(
            f"ERROR: Delete target is not in final dictionary: "
            f"{language}: {target}"
        )

    if delete_key in seen_delete_keys:
        raise SystemExit(
            f"ERROR: Duplicate delete key: "
            f"{language}: {delete_key}"
        )

    seen_delete_keys.add(delete_key)
    entry_count += 1

print(f"Delete validation OK: {entry_count} entries")
PY
}

