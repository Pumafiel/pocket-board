#!/usr/bin/env bash

set -euo pipefail

# ============================================================
# PocketBoard dictionary generator
#
# Design goals:
#   - Hunspell dictionaries are vocabulary sources only.
#   - NEVER validate candidates word-by-word with hunspell -a.
#   - Unicode/NFC-safe vocabulary.
#   - Preserve Spanish accents and Argentine voseo.
#   - Frequency-first vocabulary selection.
#   - Curated mandatory vocabulary is always preserved.
#   - Accent-aware filtering for noisy unaccented FrequencyWords
#     variants in Spanish.
#   - "manana" is explicitly excluded from es-AR.
#   - Final .dict files are the sole source for .deletes.
#   - Maximum delete distance is 2.
#   - Deterministic output.
#   - No shell pipelines that can fail because of SIGPIPE.
#   - All generated output is written to the Android assets directory.
# ============================================================

