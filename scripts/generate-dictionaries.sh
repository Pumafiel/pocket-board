# ------------------------------------------------------------
# Extract Hunspell base words
#
# IMPORTANT:
# Hunspell is NOT used to validate candidates.
# The .dic files are treated purely as vocabulary sources.
# ------------------------------------------------------------

extract_hunspell_words() {
    local language="$1"
    local source="$2"
    local destination="$3"

    python3 - "${source}" "${destination}" <<'PY'
import sys
import unicodedata
from pathlib import Path

source = Path(sys.argv[1])
destination = Path(sys.argv[2])

count = 0

with source.open(
    "r",
    encoding="utf-8",
    errors="replace"
) as src, destination.open(
    "w",
    encoding="utf-8",
    newline="\n"
) as dst:

    first = True

    for raw in src:
        line = raw.rstrip("\r\n")

        if first:
            first = False
            continue

        if not line:
            continue

        # Hunspell dictionary entries can contain flags after "/".
        word = line.split("/", 1)[0]

        word = unicodedata.normalize("NFC", word).lower()

        if word:
            dst.write(word + "\n")
            count += 1

print(count)
PY
}

# ------------------------------------------------------------
# Extract FrequencyWords
# ------------------------------------------------------------

extract_frequencywords() {
    local source="$1"
    local destination="$2"

    python3 - "${source}" "${destination}" "${SOURCE_MAX_ENTRIES}" <<'PY'
import sys
import unicodedata
from pathlib import Path

source = Path(sys.argv[1])
destination = Path(sys.argv[2])
limit = int(sys.argv[3])

def valid_token(word):
    word = unicodedata.normalize("NFC", word).lower()

    if not word:
        return None

    if len(word) > 64:
        return None

    if any(ch.isspace() for ch in word):
        return None

    for ch in word:
        category = unicodedata.category(ch)

        if ch.isalpha():
            continue

        if category.startswith("M"):
            continue

        if ch in ("'", "’", "-"):
            continue

        return None

    return word

count = 0

with source.open(
    "r",
    encoding="utf-8",
    errors="replace"
) as src, destination.open(
    "w",
    encoding="utf-8",
    newline="\n"
) as dst:

    for raw in src:
        if count >= limit:
            break

        line = raw.strip()

        if not line:
            continue

        parts = line.split()

        if not parts:
            continue

        word = valid_token(parts[0])

        if word is None:
            continue

        dst.write(word + "\n")
        count += 1

print(count)
PY
}

