# ------------------------------------------------------------
# Build final vocabulary
#
# Priority:
#   1. FrequencyWords / Leipzig
#   2. Hunspell source
#   3. Curated mandatory words
#
# The final limit is enforced while guaranteeing every mandatory
# word remains present.
#
# Spanish accent handling:
#
# FrequencyWords can contain ASCII spellings where the real
# Spanish spelling requires a diacritic, for example:
#
#   mananas  -> mañanas
#   deberia  -> debería
#
# We build an O(N) set of accent-folded keys from Hunspell's
# accented vocabulary. Only the noisy FrequencyWords candidate
# is suppressed. Hunspell itself remains authoritative and is
# still added normally afterward.
#
# This avoids word-by-word Hunspell validation completely.
# ------------------------------------------------------------

build_final_vocabulary() {
    local language="$1"
    local frequency_source="$2"
    local hunspell_source="$3"
    local core_source="$4"
    local destination="$5"

    python3 - "${language}" "${frequency_source}" "${hunspell_source}" "${core_source}" "${destination}" "${SOURCE_MAX_ENTRIES}" <<'PY'
import sys
import unicodedata
from pathlib import Path

language = sys.argv[1]
frequency_source = Path(sys.argv[2])
hunspell_source = Path(sys.argv[3])
core_source = Path(sys.argv[4])
destination = Path(sys.argv[5])
limit = int(sys.argv[6])

# ------------------------------------------------------------
# Explicit exclusions.
#
# These are spelling forms that must never enter the final
# Spanish dictionary, regardless of source.
# ------------------------------------------------------------

excluded = {
    "es-AR": {
        "manana",
        "mananas",
        "deberia",
    },
    "en-en": set(),
    "de-de": set(),
}

# ------------------------------------------------------------
# Normalization
# ------------------------------------------------------------

def normalize_token(word):
    word = unicodedata.normalize("NFC", word).lower()

    if not word:
        return None

    if len(word) > 64:
        return None

    if any(ch.isspace() for ch in word):
        return None

    for ch in word:
        category = unicodedata.category(ch)

        if ch.isalpha():
            continue

        if category.startswith("M"):
            continue

        if ch in ("'", "’", "-"):
            continue

        return None

    return word

# ------------------------------------------------------------
# Accent folding
#
# Examples:
#
#   mañana   -> manana
#   mañanas  -> mananas
#   debería  -> deberia
#   tenés    -> tenes
#
# This is only used to identify ASCII spellings that collide
# with an accented Spanish spelling.
# ------------------------------------------------------------

def accent_key(word):
    decomposed = unicodedata.normalize("NFD", word)

    return "".join(
        ch
        for ch in decomposed
        if not unicodedata.category(ch).startswith("M")
    )

def has_diacritic(word):
    return accent_key(word) != word

# ------------------------------------------------------------
# Read a complete source.
# ------------------------------------------------------------

def read_words(path):
    result = []

    with path.open(
        "r",
        encoding="utf-8",
        errors="replace"
    ) as fh:

        for raw in fh:
            word = raw.rstrip("\r\n")

            if not word:
                continue

            word = normalize_token(word)

            if word is None:
                continue

            if word in excluded[language]:
                continue

            result.append(word)

    return result

# ------------------------------------------------------------
# Read Hunspell first.
#
# Hunspell is still ONLY a vocabulary source.
# It is never executed as a validator.
# ------------------------------------------------------------

hunspell_words = read_words(hunspell_source)

hunspell_set = set(hunspell_words)

# ------------------------------------------------------------
# Build accent collision keys from Hunspell.
#
# For Spanish:
#
#   accented Hunspell word -> accent_key
#
# Example:
#
#   mañanas -> mananas
#   debería -> deberia
#
# This operation is O(N).
# ------------------------------------------------------------

accented_hunspell_keys = set()

if language == "es-AR":
    for word in hunspell_words:
        if has_diacritic(word):
            accented_hunspell_keys.add(
                accent_key(word)
            )

# ------------------------------------------------------------
# Read FrequencyWords.
#
# FrequencyWords is the noisy corpus source. If it contains
# an ASCII word whose accent-folded key corresponds to an
# accented Hunspell spelling, discard that FrequencyWords
# candidate.
#
# IMPORTANT:
# This does NOT remove words from Hunspell.
# Hunspell remains authoritative as a vocabulary source.
# ------------------------------------------------------------

frequency_words = []

accent_filtered_frequency_count = 0

with frequency_source.open(
    "r",
    encoding="utf-8",
    errors="replace"
) as fh:

    for raw in fh:
        word = raw.rstrip("\r\n")

        if not word:
            continue

        word = normalize_token(word)

        if word is None:
            continue

        if word in excluded[language]:
            continue

        if (
            language == "es-AR"
            and word.isascii()
            and accent_key(word) in accented_hunspell_keys
        ):
            accent_filtered_frequency_count += 1
            continue

        frequency_words.append(word)

# ------------------------------------------------------------
# Core vocabulary.
# ------------------------------------------------------------

core_words = read_words(core_source)

# ------------------------------------------------------------
# Merge sources in priority order.
#
#   1. FrequencyWords / Leipzig
#   2. Hunspell
#   3. Core
# ------------------------------------------------------------

ordered = []
seen = set()

def append_unique(words):
    for word in words:
        if word in seen:
            continue

        seen.add(word)
        ordered.append(word)

append_unique(frequency_words)
append_unique(hunspell_words)
append_unique(core_words)

# ------------------------------------------------------------
# IMPORTANT:
#
# At this point we perform a FINAL Spanish accent cleanup.
#
# This catches cases where the unaccented form came from
# Hunspell itself or another source.
#
# Only the explicitly problematic ASCII forms are removed
# here. We do NOT globally remove every ASCII/accent pair,
# because valid Spanish words can legitimately coexist:
#
#   papa / papá
#   si / sí
#   el / él
#   solo / sólo
#
# The broad accent collision filtering already happens against
# FrequencyWords above.
# ------------------------------------------------------------

final_excluded = set(excluded[language])

if language == "es-AR":
    final_excluded.update({
        "manana",
        "mananas",
        "deberia",
    })

# ------------------------------------------------------------
# Prepare mandatory vocabulary.
# ------------------------------------------------------------

core_unique = []

for word in core_words:
    if word not in core_unique:
        core_unique.append(word)

core_set = set(core_unique)

# ------------------------------------------------------------
# Select according to source priority.
# ------------------------------------------------------------

selected = []
selected_set = set()

for word in ordered:
    if word in final_excluded:
        continue

    if word in selected_set:
        continue

    selected.append(word)
    selected_set.add(word)

    if len(selected) >= limit:
        break

# ------------------------------------------------------------
# Guarantee every mandatory word survives the hard limit.
# ------------------------------------------------------------

missing_core = [
    word
    for word in core_unique
    if word not in selected_set
]

for required_word in missing_core:

    # Required words must never be excluded.
    if required_word in final_excluded:
        raise SystemExit(
            f"ERROR: Required word conflicts with exclusion: "
            f"{language}: {required_word}"
        )

    replacement_index = None

    for index in range(len(selected) - 1, -1, -1):
        candidate = selected[index]

        if candidate not in core_set:
            replacement_index = index
            break

    if replacement_index is None:

        if len(selected) < limit:
            selected.append(required_word)
            selected_set.add(required_word)
            continue

        raise SystemExit(
            f"ERROR: Mandatory vocabulary exceeds limit for {language}"
        )

    old_word = selected[replacement_index]

    selected_set.discard(old_word)

    selected[replacement_index] = required_word

    selected_set.add(required_word)

# ------------------------------------------------------------
# Final deterministic normalization/deduplication.
# ------------------------------------------------------------

final_words = []
final_seen = set()

for word in selected:

    word = normalize_token(word)

    if word is None:
        continue

    if word in final_excluded:
        continue

    if word in final_seen:
        continue

    final_seen.add(word)
    final_words.append(word)

# ------------------------------------------------------------
# Enforce maximum vocabulary size.
# ------------------------------------------------------------

if len(final_words) > limit:
    final_words = final_words[:limit]

final_set = set(final_words)

# ------------------------------------------------------------
# Final mandatory-word verification.
#
# This is a set membership check, not Hunspell validation.
# ------------------------------------------------------------

for required_word in core_unique:

    if required_word not in final_set:
        raise SystemExit(
            f"ERROR: Required word was lost while building "
            f"{language}: {required_word}"
        )

# ------------------------------------------------------------
# Explicit Spanish regression protection.
# ------------------------------------------------------------

if language == "es-AR":

    forbidden_spanish = {
        "manana",
        "mananas",
        "deberia",
    }

    forbidden_present = (
        forbidden_spanish.intersection(final_set)
    )

    if forbidden_present:
        words = ", ".join(
            sorted(forbidden_present)
        )

        raise SystemExit(
            f"ERROR: Forbidden Spanish spelling(s) reached "
            f"final vocabulary: {words}"
        )

    required_spanish = {
        "mañana",
        "mañanas",
        "debería",
    }

    missing_spanish = (
        required_spanish.difference(final_set)
    )

    if missing_spanish:
        words = ", ".join(
            sorted(missing_spanish)
        )

        raise SystemExit(
            f"ERROR: Required Spanish accented spelling(s) "
            f"missing: {words}"
        )

# ------------------------------------------------------------
# Write final vocabulary.
# ------------------------------------------------------------

with destination.open(
    "w",
    encoding="utf-8",
    newline="\n"
) as dst:

    for word in final_words:
        dst.write(word + "\n")

print(f"Frequency source: {len(frequency_words)}")
print(f"Hunspell source:  {len(hunspell_words)}")
print(f"Core vocabulary:  {len(core_unique)}")
print(
    "Accent-filtered FrequencyWords: "
    f"{accent_filtered_frequency_count}"
)
print(f"Final vocabulary: {len(final_words)}")
PY
}
