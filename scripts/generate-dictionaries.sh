import sys
import unicodedata
from pathlib import Path

dict_paths = [
    Path(sys.argv[1]),
    Path(sys.argv[2]),
    Path(sys.argv[3]),
]

delete_paths = [
    Path(sys.argv[4]),
    Path(sys.argv[5]),
    Path(sys.argv[6]),
]

for path in dict_paths:
