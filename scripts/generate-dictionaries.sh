check_delete_budget() {
    local deletes="$1"
    local budget="$2"
    local language="$3"

    local total_lines
    local entry_count

    total_lines="$(wc -l < "${deletes}")"
    entry_count=$((total_lines - 4))

    if (( entry_count < 0 )); then
        die "Invalid deletes file line count: ${language}"
    fi

    if (( entry_count > budget )); then
        die "Delete budget exceeded: ${language}: ${entry_count} > ${budget}"
    fi

    echo "Delete budget OK: ${language}: ${entry_count}/${budget}"
}

